create extension if not exists pgcrypto;

create table if not exists public.referrers (
  id uuid primary key default gen_random_uuid(),
  code text unique not null,
  name text,
  contact text,
  payout_method text,
  pin_hash text,
  failed_attempts integer not null default 0,
  locked_until timestamptz,
  created_ip text,
  created_at timestamptz not null default now()
);

-- Si ya habías ejecutado una versión anterior del SQL, estas líneas agregan
-- las columnas nuevas sin borrar datos.
alter table public.referrers add column if not exists pin_hash text;
alter table public.referrers add column if not exists failed_attempts integer not null default 0;
alter table public.referrers add column if not exists locked_until timestamptz;

create table if not exists public.referral_visits (
  id bigint generated by default as identity primary key,
  referrer_code text not null references public.referrers(code) on delete cascade,
  visitor_id text not null,
  ip_hash text,
  path text,
  created_at timestamptz not null default now(),
  unique (referrer_code, visitor_id)
);

alter table public.referral_visits add column if not exists ip_hash text;

create table if not exists public.referral_events (
  id bigint generated by default as identity primary key,
  referrer_code text not null references public.referrers(code) on delete cascade,
  visitor_id text not null,
  ip_hash text,
  event_type text not null check (event_type in ('ad_click', 'download')),
  app_slug text,
  created_at timestamptz not null default now()
);

alter table public.referral_events add column if not exists ip_hash text;

-- Evita contar dos veces la misma descarga de la misma app por el mismo visitante.
create unique index if not exists referral_download_unique
  on public.referral_events (referrer_code, visitor_id, app_slug)
  where event_type = 'download';

create table if not exists public.referral_payouts (
  id bigint generated by default as identity primary key,
  referrer_code text not null references public.referrers(code) on delete cascade,
  amount_cents integer not null check (amount_cents > 0),
  method text,
  contact text,
  status text not null default 'pending' check (status in ('pending', 'paid', 'rejected')),
  requested_at timestamptz not null default now(),
  paid_at timestamptz
);

create index if not exists referral_visits_code_idx on public.referral_visits (referrer_code);
create index if not exists referral_events_code_idx on public.referral_events (referrer_code);
create index if not exists referral_events_visitor_idx on public.referral_events (referrer_code, visitor_id, created_at);
create index if not exists referral_visits_ip_idx on public.referral_visits (ip_hash, created_at);
create index if not exists referral_events_ip_idx on public.referral_events (ip_hash, created_at);
create index if not exists referral_payouts_code_idx on public.referral_payouts (referrer_code);

-- RLS: el acceso público queda bloqueado. Solo las API routes con la
-- service_role key pueden leer/escribir. No crees políticas públicas.
alter table public.referrers enable row level security;
alter table public.referral_visits enable row level security;
alter table public.referral_events enable row level security;
alter table public.referral_payouts enable row level security;
